-- Livings core schema. Written to run on PostgreSQL and on H2 in PostgreSQL mode (local dev / tests).

CREATE TABLE universities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200)     NOT NULL UNIQUE,
    city        VARCHAR(100)     NOT NULL,
    state       VARCHAR(2)       NOT NULL,
    latitude    DOUBLE PRECISION NOT NULL,
    longitude   DOUBLE PRECISION NOT NULL,
    website     VARCHAR(255)
);
CREATE INDEX idx_universities_state ON universities (state);

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(255) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    full_name      VARCHAR(120) NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    phone          VARCHAR(30),
    gender         VARCHAR(30),
    home_country   VARCHAR(80),
    university_id  BIGINT REFERENCES universities (id),
    languages      VARCHAR(255),
    bio            VARCHAR(2000),
    avatar_url     VARCHAR(1000),
    edu_email      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE listings (
    id                                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id                          BIGINT        NOT NULL REFERENCES users (id),
    title                             VARCHAR(150)  NOT NULL,
    description                       VARCHAR(5000) NOT NULL,
    category                          VARCHAR(30)   NOT NULL,
    room_type                         VARCHAR(30)   NOT NULL,
    property_type                     VARCHAR(30)   NOT NULL,
    gender_preference                 VARCHAR(30)   NOT NULL,
    status                            VARCHAR(20)   NOT NULL,
    street_address                    VARCHAR(255)  NOT NULL,
    unit                              VARCHAR(50),
    city                              VARCHAR(100)  NOT NULL,
    state                             VARCHAR(2)    NOT NULL,
    zip_code                          VARCHAR(10)   NOT NULL,
    latitude                          DOUBLE PRECISION,
    longitude                         DOUBLE PRECISION,
    nearest_university_id             BIGINT REFERENCES universities (id),
    monthly_rent                      NUMERIC(10, 2) NOT NULL,
    security_deposit                  NUMERIC(10, 2),
    utilities_included                BOOLEAN       NOT NULL DEFAULT FALSE,
    estimated_utilities               NUMERIC(10, 2),
    bedrooms                          INTEGER       NOT NULL,
    bathrooms                         NUMERIC(3, 1) NOT NULL,
    current_occupants                 INTEGER       NOT NULL DEFAULT 0,
    available_from                    DATE          NOT NULL,
    min_lease_months                  INTEGER       NOT NULL,
    furnished                         BOOLEAN       NOT NULL DEFAULT FALSE,
    pets_allowed                      BOOLEAN       NOT NULL DEFAULT FALSE,
    no_ssn_required                   BOOLEAN       NOT NULL DEFAULT FALSE,
    no_credit_history_required        BOOLEAN       NOT NULL DEFAULT FALSE,
    international_guarantor_accepted  BOOLEAN       NOT NULL DEFAULT FALSE,
    virtual_tour_available            BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at                        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at                        TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_listings_search ON listings (status, state, city);
CREATE INDEX idx_listings_rent ON listings (monthly_rent);
CREATE INDEX idx_listings_geo ON listings (latitude, longitude);
CREATE INDEX idx_listings_owner ON listings (owner_id);

CREATE TABLE listing_photos (
    listing_id  BIGINT        NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    position    INTEGER       NOT NULL,
    url         VARCHAR(1000) NOT NULL,
    PRIMARY KEY (listing_id, position)
);

CREATE TABLE listing_amenities (
    listing_id  BIGINT      NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    amenity     VARCHAR(40) NOT NULL,
    PRIMARY KEY (listing_id, amenity)
);

CREATE TABLE roommate_profiles (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT        NOT NULL UNIQUE REFERENCES users (id),
    headline           VARCHAR(150)  NOT NULL,
    budget_min         NUMERIC(10, 2) NOT NULL,
    budget_max         NUMERIC(10, 2) NOT NULL,
    preferred_state    VARCHAR(2)    NOT NULL,
    preferred_city     VARCHAR(100),
    university_id      BIGINT REFERENCES universities (id),
    move_in_date       DATE          NOT NULL,
    lease_months       INTEGER,
    gender_preference  VARCHAR(30)   NOT NULL,
    smoker             BOOLEAN       NOT NULL DEFAULT FALSE,
    has_pets           BOOLEAN       NOT NULL DEFAULT FALSE,
    sleep_schedule     VARCHAR(30),
    cleanliness_level  INTEGER,
    bio                VARCHAR(2000),
    active             BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_roommate_profiles_search ON roommate_profiles (active, preferred_state, preferred_city);

CREATE TABLE favorites (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    listing_id  BIGINT NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_favorites_user_listing UNIQUE (user_id, listing_id)
);

-- A conversation is either about a listing (listing_id set) or a direct roommate-match chat (listing_id null).
CREATE TABLE conversations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id       BIGINT REFERENCES listings (id),
    initiator_id     BIGINT NOT NULL REFERENCES users (id),
    recipient_id     BIGINT NOT NULL REFERENCES users (id),
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_message_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_conversations_initiator ON conversations (initiator_id, last_message_at);
CREATE INDEX idx_conversations_recipient ON conversations (recipient_id, last_message_at);
CREATE INDEX idx_conversations_listing ON conversations (listing_id);

CREATE TABLE messages (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  BIGINT        NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    sender_id        BIGINT        NOT NULL REFERENCES users (id),
    body             VARCHAR(4000) NOT NULL,
    sent_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    read_at          TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_messages_conversation ON messages (conversation_id, sent_at);
